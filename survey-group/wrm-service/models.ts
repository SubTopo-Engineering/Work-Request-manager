import mongoose, { Schema } from 'mongoose';

/** Allowed lifecycle statuses of a Work Request. */
export const STATUSES = ['Reçu', 'En cours', 'Terminé', 'Archivé'] as const;

/** Status of a Work Request. */
export type RequestStatus = (typeof STATUSES)[number];

/** File categories attached to a Work Request. */
export const FILE_CATEGORIES = ['original', 'document', 'photo', 'raw', 'processing', 'final'] as const;

/** Category of a file attached to a request. */
export type FileCategory = (typeof FILE_CATEGORIES)[number];

/** Metadata of a file attached to a request (binary stored separately). */
export interface FileMeta {
  _id?: mongoose.Types.ObjectId;
  name: string;
  mimeType: string;
  size: number;
  category: FileCategory;
  archivePath: string;
  blobId: mongoose.Types.ObjectId;
  uploadedAt: Date;
  version: number;
}

/** One entry of the full history of a request. */
export interface HistoryEntry {
  at: Date;
  action: string;
  details?: string;
  by?: string;
}

/** A Work Request document. */
export interface WorkRequestDoc {
  number: string;
  seq: number;
  year: number;
  receivedDate: Date;
  subject: string;
  department: string;
  site?: string;
  description: string;
  plannedDate?: Date | null;
  completedDate?: Date | null;
  operator: string;
  status: RequestStatus;
  ocrText?: string;
  files: FileMeta[];
  history: HistoryEntry[];
  createdAt?: Date;
  updatedAt?: Date;
}

const fileSchema = new Schema<FileMeta>({
  name: String,
  mimeType: String,
  size: Number,
  category: { type: String, enum: FILE_CATEGORIES },
  archivePath: String,
  blobId: Schema.Types.ObjectId,
  uploadedAt: Date,
  version: { type: Number, default: 1 },
});

const historySchema = new Schema<HistoryEntry>(
  { at: Date, action: String, details: String, by: String },
  { _id: false }
);

const requestSchema = new Schema<WorkRequestDoc>(
  {
    number: { type: String, unique: true, index: true },
    seq: Number,
    year: { type: Number, index: true },
    receivedDate: Date,
    subject: { type: String, default: '' },
    department: { type: String, default: '' },
    site: { type: String, default: '' },
    description: { type: String, default: '' },
    plannedDate: Date,
    completedDate: Date,
    operator: { type: String, default: '' },
    status: { type: String, enum: STATUSES, default: 'Reçu' },
    ocrText: String,
    files: [fileSchema],
    history: [historySchema],
  },
  { timestamps: true }
);

/** Work Request model. */
export const WorkRequest: mongoose.Model<any> = mongoose.models.WorkRequest || mongoose.model<WorkRequestDoc>('WorkRequest', requestSchema);

/** Binary file storage model. */
export const FileBlob: mongoose.Model<any> =
  mongoose.models.FileBlob ||
  mongoose.model('FileBlob', new Schema({ data: Buffer, mimeType: String, name: String }));

/** Per-year counter for SR numbering. */
export const Counter: mongoose.Model<any> =
  mongoose.models.Counter || mongoose.model('Counter', new Schema({ _id: String, value: Number }));

/** Application settings. */
export interface SettingsDoc {
  _id: string;
  language: string;
  ocrLanguage: string;
  operators: string[];
  departments: string[];
  autoArchiveDays: number;
  rootFolder: string;
  lastDailyRun?: Date;
}

/** Settings model (single document with _id "main"). */
export const Settings: mongoose.Model<any> =
  mongoose.models.Settings ||
  mongoose.model<SettingsDoc>(
    'Settings',
    new Schema<SettingsDoc>({
      _id: String,
      language: { type: String, default: 'fr' },
      ocrLanguage: { type: String, default: 'fra+eng' },
      operators: [String],
      departments: [String],
      autoArchiveDays: { type: Number, default: 30 },
      rootFolder: { type: String, default: 'D:\\SurveyGroup\\Work Requests' },
      lastDailyRun: Date,
    })
  );

/** Daily report snapshot model generated by the automation job. */
export const ReportSnapshot: mongoose.Model<any> =
  mongoose.models.ReportSnapshot ||
  mongoose.model(
    'ReportSnapshot',
    new Schema({ day: { type: String, unique: true }, generatedAt: Date, stats: Schema.Types.Mixed })
  );
